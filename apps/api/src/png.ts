export function renderMyspotPng(lines: string[], dark: boolean, scale: number): Buffer {
  const width = 320 * scale;
  const height = 64 * scale;
  const png = new PNG({width, height});
  const bg = dark ? [18, 22, 28, 255] : [245, 247, 250, 255];
  const fg = dark ? [232, 236, 241, 255] : [28, 36, 46, 255];
  for (let i = 0; i < png.data.length; i += 4) {
    png.data[i] = bg[0];
    png.data[i + 1] = bg[1];
    png.data[i + 2] = bg[2];
    png.data[i + 3] = bg[3];
  }
  lines.slice(0, 2).forEach((line, row) => drawText(png, line.toUpperCase(), 8 * scale, (10 + row * 24) * scale, fg, scale));
  return PNG.sync.write(png);
}

function drawText(png: PNG, text: string, x: number, y: number, color: number[], scale: number) {
  let cursor = x;
  for (const ch of text) {
    const glyph = GLYPHS[ch] || GLYPHS[' '];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if ((glyph[row] & (1 << (4 - col))) === 0) continue;
        fill(png, cursor + col * scale, y + row * scale, scale, color);
      }
    }
    cursor += 6 * scale;
    if (cursor > png.width - 8) break;
  }
}

function fill(png: PNG, x: number, y: number, scale: number, color: number[]) {
  for (let dy = 0; dy < scale; dy++) {
    for (let dx = 0; dx < scale; dx++) {
      const px = x + dx;
      const py = y + dy;
      if (px < 0 || py < 0 || px >= png.width || py >= png.height) continue;
      const i = (py * png.width + px) * 4;
      png.data[i] = color[0];
      png.data[i + 1] = color[1];
      png.data[i + 2] = color[2];
      png.data[i + 3] = color[3];
    }
  }
}

export function deviceIdForToken(token: string, stored?: string): string {
  if (stored) return stored;
  return createHash('sha256').update(token).digest('hex').slice(0, 24);
}
